// gen-yard: assembles the Yard scope of @hackbuild/agents-views.
// The yard's modules (packages/agents-views/yard, listed in order in yard/scope.json) share one
// scope, the layout the dog simulator's golden traces were recorded on. This joins them into one
// function, runYard(ENV), in packages/agents-views/src/yard/scope.js, beside the markup, the
// stylesheet (every selector scoped to the yard root and its bar with :where, so specificity holds)
// and the cortex worker body as strings. src/yard/scope.d.ts types what leaves it.
//   node tools/gen-yard.mjs           write src/yard/scope.js
//   node tools/gen-yard.mjs --dist    also copy scope.js and scope.d.ts into dist/yard/
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { pathToFileURL } from "node:url";

const root = resolve(import.meta.dirname, "..");
const pkg = join(root, "packages", "agents-views");
const Y = join(pkg, "yard");

/** Prefixes every selector with `:where(.hb-yard,.hb-yard-bar) ` unless it names the root itself. */
export function scopeCss(css) {
  const out = [];
  let i = 0;
  const scopeSel = (sel) =>
    sel
      .split(",")
      .map((s) => s.trim())
      .filter(Boolean)
      .map((s) => (/^\.hb-yard(-bar)?\b/.test(s) ? s : `:where(.hb-yard,.hb-yard-bar) ${s}`))
      .join(",");
  // one level of blocks: rules, and @media or @supports holding rules
  const block = (end) => {
    while (i < css.length) {
      const ws = css.slice(i).match(/^\s*/)[0];
      if (ws) { out.push(ws); i += ws.length; continue; }
      if (css.startsWith("/*", i)) {
        const j = css.indexOf("*/", i) + 2;
        out.push(css.slice(i, j));
        i = j;
        continue;
      }
      if (css[i] === "}") {
        if (end) { out.push("}"); i++; return; }
        throw new Error(`gen-yard: a stray } at ${i}`);
      }
      const open = css.indexOf("{", i);
      if (open < 0) { out.push(css.slice(i)); i = css.length; return; }
      const head = css.slice(i, open);
      const lead = head.match(/^\s*/)[0];
      const sel = head.trim();
      i = open + 1;
      if (/^@(media|supports|container)\b/.test(sel)) {
        out.push(`${lead}${sel}{`);
        block(true);
        continue;
      }
      const close = css.indexOf("}", i);
      const body = css.slice(i, close);
      i = close + 1;
      out.push(`${lead}${sel.startsWith("@") ? sel : scopeSel(sel)}{${body}}`);
    }
  };
  block(false);
  return out.join("");
}

export function yardSource() {
  const order = JSON.parse(readFileSync(join(Y, "scope.json"), "utf8"));
  const parts = order.map((f) => `// ---- yard/${f}\n` + readFileSync(join(Y, f), "utf8"));
  const text = (f) => JSON.stringify(readFileSync(join(Y, f), "utf8"));
  return [
    "// generated by tools/gen-yard.mjs from packages/agents-views/yard; edit those files, not this one",
    "import * as THREE from 'three/webgpu';",
    "import { GLTFLoader } from 'three/addons/loaders/GLTFLoader.js';",
    "import { OrbitControls } from 'three/addons/controls/OrbitControls.js';",
    "import * as HMN from '@hackbuild/motion-net';",
    "import * as HGAIT from '@hackbuild/gait';",
    "import * as HTUNE from '@hackbuild/tunables';",
    "import * as HSENSE from '@hackbuild/senses';",
    "import * as HDRIVE from '@hackbuild/drives';",
    "import * as HCAM from '@hackbuild/cameras';",
    "import * as HWEIGHT from '@hackbuild/weights';",
    "import * as HBV from '@virgilvox/hackbuild-ui/vanilla';",
    `export const YARD_CSS = ${JSON.stringify(scopeCss(readFileSync(join(Y, "yard.css"), "utf8")))};`,
    `export const YARD_HTML = ${text("yard.html")};`,
    `export const YARD_BAR_HTML = ${text("bar.html")};`,
    `const CORTEX_WORKER = ${text("cortex-worker.js")};`,
    "export function runYard(ENV) {",
    "const RAPIER_MODULE = ENV.rapier;",
    "const SUITE_URL = ENV.suiteUrl;",
    // the scope's window listeners, timers and observers go through the host's ledger, so
    // dispose removes them
    "const addEventListener = ENV.on, setTimeout = ENV.setTimeout, setInterval = ENV.setInterval, ResizeObserver = ENV.ResizeObserver;",
    "{",
    ...parts,
    "}",
    "}",
    "",
  ].join("\n");
}

function main(argv) {
  const out = join(pkg, "src", "yard");
  mkdirSync(out, { recursive: true });
  const src = yardSource();
  writeFileSync(join(out, "scope.js"), src);
  console.log(`gen-yard: src/yard/scope.js ${Buffer.byteLength(src)} bytes (measured)`);
  if (argv.includes("--dist")) {
    mkdirSync(join(pkg, "dist", "yard"), { recursive: true });
    for (const f of ["scope.js", "scope.d.ts"]) copyFileSync(join(out, f), join(pkg, "dist", "yard", f));
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) main(process.argv.slice(2));
