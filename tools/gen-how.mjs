// gen-how: writes the skeleton of packages/<name>/how.ts, the one source of
// the "how this works" fold (design D8). The package page and the suite
// both render it. From package.json and the README it takes the name, the
// one line of what the package is, the install lines, the first code block
// under "## Use" and the links; the "how" paragraphs start as the README
// intro and are rewritten by hand. An existing how.ts is left alone unless
// --force is passed. It also writes tools/how-check.ts, which imports every
// how.ts against the shape so `tsc -p tsconfig.how.json` checks them all.
// Usage: node tools/gen-how.mjs [--force] [name ...]
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const SITE = "https://hackbuild.github.io/hackbuild-agents/";
const REPO = "https://github.com/hackbuild/hackbuild-agents";
const args = process.argv.slice(2);
const force = args.includes("--force");
const only = args.filter((a) => !a.startsWith("--"));
const pkgs = readdirSync(join(root, "packages")).filter((n) => existsSync(join(root, "packages", n, "package.json")));
const pages = new Set(JSON.parse(readFileSync(join(root, "examples", "pages.json"), "utf8")).pages.map((p) => p.name));

const str = (s) => JSON.stringify(s);
// a template literal keeps the code sample readable in the file
const tpl = (s) => "`" + s.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${") + "`";

function skeleton(name) {
  const dir = join(root, "packages", name);
  const pj = JSON.parse(readFileSync(join(dir, "package.json"), "utf8"));
  const md = readFileSync(join(dir, "README.md"), "utf8");
  const intro = md.split(/\n\n/)[1]?.replace(/\s*\n\s*/g, " ").trim() ?? "";
  const use = md.split(/^## Use\s*$/m)[1] ?? "";
  const code = /```(\w*)\n([\s\S]*?)```/.exec(use);
  return `// how this works, ${pj.name}: the fold on the package page and in the suite.
// Data only, kept out of the runtime entry; tsconfig.how.json checks it.
export default {
  name: ${str(pj.name)},
  what: ${str(pj.description)},
  how: [
    ${str(intro)},
  ],
  packages: [${str(pj.name)}],
  install: ${str(`npm install ${pj.name}`)},
  today: ${str(`git clone ${REPO} && cd hackbuild-agents && npm ci && npm run build -w ${pj.name}`)},
  published: false,
  lang: ${str(code?.[1] || "ts")},
  code: ${tpl((code?.[2] ?? "").trimEnd())},
  links: {
    page: ${str(SITE + name + "/")},
    source: ${str(`${REPO}/tree/main/packages/${name}`)},
  },
};
`;
}

let wrote = 0;
for (const name of only.length ? only : pkgs) {
  const file = join(root, "packages", name, "how.ts");
  if (existsSync(file) && !force) continue;
  writeFileSync(file, skeleton(name));
  wrote++;
}

const id = (n) => n.replace(/\W/g, "_");
writeFileSync(
  join(root, "tools", "how-check.ts"),
  `// generated by tools/gen-how.mjs: every packages/<name>/how.ts against the fold shape.
// The shape is the HbHow props of hackbuild-ui plus name, what and how.
export interface HowSource {
  name: string;
  /** one line: what the package is */
  what: string;
  /** a few short paragraphs: how it works */
  how: string[];
  packages: string[];
  install: string;
  today?: string;
  published?: boolean;
  lang?: string;
  code: string;
  links: { page?: string; source?: string };
}
${pkgs.map((n) => `import ${id(n)} from "../packages/${n}/how.js";`).join("\n")}

export const all: Record<string, HowSource> = { ${pkgs.map((n) => `${str(n)}: ${id(n)}`).join(", ")} };
`,
);
console.log(`gen-how: ${wrote} how.ts written, ${pkgs.length} in tools/how-check.ts, ${pkgs.filter((n) => !pages.has(n)).length} with no page`);
